import numpy as np
import pandas as pd

class Evaluator:
    def __init__(self, y_pred: pd.Series | np.ndarray, targets: pd.Series | np.ndarray):
        '''Initialize an evaluator with predicted and actual target values.

        Stores the predictions and corresponding target values for calculating evaluation metrics.

        Args:
            y_pred: Predicted values generated by a machine learning model.
            targets: Actual target values corresponding to the predictions.
        '''

        self.set(y_pred, targets)

    def set(self, y_pred: pd.Series | np.ndarray, targets: pd.Series | np.ndarray):
        '''Set this evaluator's predictions and actual target values to use for calculations.

        Allows the same Evaluator instance to be reused with different prediction results. Predictions and targets must each
        be one-dimensional and contain the same number of samples in matching order.

        Args:
            y_pred: Predicted class labels or regression values.
            targets: Actual class labels or regression values.

        Returns:
            None. Stores the arrays in self.y_ and self.t_, and the sample count in self.total_.

        Raises:
            ValueError: If the inputs are not one-dimensional, have different lengths, or contain no samples.
        '''

        if y_pred.ndim != 1 or targets.ndim != 1:
            raise ValueError("y_pred and targets must both be 1D arrays!")

        if y_pred.shape != targets.shape:
            raise ValueError("y_pred and targets must have matching shapes!")

        if y_pred.size == 0:
            raise ValueError("y_pred and targets cannot be empty!")

        self.y_ = y_pred.to_numpy() if isinstance(y_pred, pd.Series) else y_pred
        self.t_ = targets.to_numpy() if isinstance(targets, pd.Series) else targets
        self.total_ = len(targets)

    def get_accuracy(self):
        '''Calculate classification accuracy for the stored predictions.

        Accuracy = (Number of correct predictions) / (Total predictions).

        Returns:
            float: Classification accuracy ranging from 0.0 to 1.0, where 1.0 indicates that every prediction was correct.

        Notes:
            This metric is intended for classification, not regression. For continuous predictions, consider MAE or MSE
            instead.
        '''

        # Creates a True/False array where True indexes are correct predictions and False are incorrect. This works
        # for any discrete classifications. Examples (1st array are the predictions, 2nd is the targets/actual):
        # [1, 1, 0] == [1, 0, 0] -> [True, False, True]
        # ["bird", "dog", "cat", "dog"] == ["bird", "cat", "dog", "dog"] -> [True, False, False, True]
        results = self.y_ == self.t_
        return results.sum() / self.total_ # NumPy treats True as 1 and False as 0, sum gets the count of correct predictions

